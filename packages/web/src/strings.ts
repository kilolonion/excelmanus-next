export function toolTitle(name: string): string {
  const t = TOOL_TITLES[name];
  if (t) return t;
  const mcp = /^mcp__(.+?)__(.+)$/.exec(name);
  if (mcp) return `${mcp[1]} · ${mcp[2]}`;
  return name === "?" ? "工具调用" : name;
}

